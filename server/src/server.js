import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import mongoSanitize from 'express-mongo-sanitize';
import mongoose from 'mongoose';
import authRoutes from './routes/auth.js';
import libRoutes from './routes/library.js';
const app = express();
app.set('trust proxy', 1);
app.use(helmet());
app.use(cors({ origin: (process.env.CLIENT_URL || 'http://localhost:5173').split(','), credentials: true }));
app.use(express.json({ limit: '100kb' }));
app.use(mongoSanitize());
app.use('/api', rateLimit({ windowMs: 15 * 60000, limit: 600 }));
app.use('/api/auth', rateLimit({ windowMs: 15 * 60000, limit: 40, message: { success: false, message: 'Too many attempts, try later' } }));
app.get('/api/health', (q, s) => s.json({ success: true, message: 'Devansh Library API is running' }));
app.use('/api/auth', authRoutes);
app.use('/api', libRoutes);
app.use((q, s) => s.status(404).json({ success: false, message: 'Not found' }));
app.use((e, q, s, n) => { console.error(e); s.status(500).json({ success: false, message: e.code === 11000 ? 'Duplicate value' : 'Something went wrong' }); });
const PORT = process.env.PORT || 5000;
mongoose.connect(process.env.MONGODB_URI).then(() => app.listen(PORT, () => console.log(`API on :${PORT}`))).catch((e) => { console.error('MongoDB connection failed:', e.message); process.exit(1); });
